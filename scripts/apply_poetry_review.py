def main() -> None:
    by = collections.defaultdict(list)
    for x in R:
        by[x[0]].append(x)
    used = set(); n = collections.Counter()
    for b in ["tang", "songci", "ke"]:
        f = ROOT / f"{b}.json"; d = json.loads(f.read_text(encoding="utf-8"))
        for p in d["pieces"]:
            if p["id"] not in by:
                continue
            pos = []
            for li, l in enumerate(p["lines"]):
                for ti, t in enumerate(l["tokens"]):
                    if t.get("punct"):
                        pos.append((t["s"], None)); continue
                    for k, c in enumerate(t["s"]):
                        pos.append((c, (li, ti, k)))
            s = "".join(c for c, _ in pos)
            for rule in by[p["id"]]:
                _, ctx, idx, py = rule; i = s.find(ctx)
                while i >= 0:
                    li, ti, k = pos[i + idx][1]; t = p["lines"][li]["tokens"][ti]; ys = t["py"].split()
                    if ys[k] != py:
                        ys[k] = py; t["py"] = " ".join(ys); n[b] += 1
                    used.add(rule); i = s.find(ctx, i + 1)
        f.write_text(json.dumps(d, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    missing = [x for x in R if x not in used]
    if missing:
        sys.exit(f"未命中: {missing}")
    print(dict(n))


if __name__ == "__main__":
    main()
