PY = {("mulan", 85): "wèi"}


def main() -> None:
    d = json.loads(KE.read_text(encoding="utf-8"))
    by = {p["id"]: [t for l in p["lines"] for t in l["tokens"]] for p in d["pieces"]}
    n = 0
    for line in FIX.strip().splitlines():
        pid, i, ch, gloss = line.split(" ", 3)
        t = by[pid][int(i)]
        if t["s"] != ch:
            sys.exit(f"字不符: {line} -> {t['s']}")
        if t["ctx"] != gloss:
            t["ctx"] = gloss; n += 1
    for (pid, i), py in PY.items():
        t = by[pid][i]
        if t["py"] != py:
            t["py"] = py; n += 1
    KE.write_text(json.dumps(d, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(n)


if __name__ == "__main__":
    main()
