RULES = R


def fix_tokens(tokens: list[dict]) -> int:
    slots = [t for t in tokens if not t.get("punct")]
    han = "".join(t["s"] for t in slots)
    n = 0
    for t in slots:
        d = DEFAULTS.get(t["s"])
        if d and t.get("py") != d:
            t["py"] = d; n += 1
    for ctx, at, py in RULES:
        start = 0
        while (i := han.find(ctx, start)) >= 0:
            if slots[i + at]["py"] != py:
                slots[i + at]["py"] = py; n += 1
            start = i + 1
    # 句末「与」在问号、叹号前读 yú（同「欤」）
    for i, t in enumerate(tokens):
        if t.get("s") == "与" and i + 1 < len(tokens) and tokens[i + 1].get("punct") and tokens[i + 1]["s"] in "？！" and t.get("py") != "yú":
            t["py"] = "yú"; n += 1
    return n
